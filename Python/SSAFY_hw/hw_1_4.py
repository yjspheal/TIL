# 사과는 영어로 apple
# 바나나는 영어로 banana
# 키위는 영어로 kiwi

korean_apple = '사과'
english_apple = 'apple'
korean_banana = '바나나'
english_banana = 'banana'
korean_kiwi = '키위'
english_kiwi = 'kiwi'
to_english = '는 영어로'

print(f'{korean_apple}{to_english} {english_apple}')
print(f'{korean_banana}{to_english} {english_banana}')
print(f'{korean_kiwi}{to_english} {english_kiwi}')